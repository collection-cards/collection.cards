export type SiteMessages = (typeof dictionaries)['en-US']

export function getMessages(locale?: string | null): SiteMessages {
  const normalized = normalizeLocale(locale) ?? defaultLocale
  const siteLocale = isSiteLocale(normalized) ? normalized : defaultLocale
  return dictionaries[siteLocale as keyof typeof dictionaries] as SiteMessages
}

export function getCardCountLabel(count: number, locale: LocaleTag) {
  const messages = getMessages(locale)
  return `${count} ${count === 1 ? messages.card : messages.cards}`
}
